import fs from 'node:fs';
import assert from 'node:assert/strict';
const harness = fs.readFileSync('verify-map.mjs', 'utf8').split('\nrun(`')[0] + '\nexport {run};';
const {run} = await import('data:text/javascript,' + encodeURIComponent(harness));
run(`{
OrbitalArrival.enabled = true;
const reset = () => { state = initial(); state.expansion = false; paused = true; FlightQueue.reset(); Simulation.debt = Simulation.wallDebt = 0; Cosmology.sync(state); };
reset();
const reserve = () => FlightSetup.preferred().arrivalFuelPercent;
assert.equal(reserve(), 50);
QuickFlight.toggle('engine');
assert.ok(!FlightSetup.read().engine && FlightSetup.read().sail && FlightSetup.read().collector);
QuickFlight.toggle('collector');
assert.ok(!FlightSetup.read().collector && FlightSetup.read().sail && !FlightSetup.read().engine);
assert.equal($('quickResult').hidden, false);
assert.equal($('quickIssue').hidden, false);
assert.equal($('quickSpeedRow').hidden, true);
assert.equal($('flightHint').hidden, true);
assert.equal(QuickFlight.issueReason, MissionPlanner.preview().reason);
$('quickIssue').onclick();
assert.ok($('dialogContent').innerHTML.includes(FlightQueue.escape(QuickFlight.issueReason)));
$('infoDialog').close();
QuickFlight.toggle('sail');
assert.ok(FlightSetup.read().engine && !FlightSetup.read().sail && !FlightSetup.read().burst);
QuickFlight.toggle('engine');
assert.ok(FlightSetup.read().engine, 'cannot turn off the only acceleration source');
QuickFlight.toggle('collector');
assert.ok(FlightSetup.read().engine && FlightSetup.read().sail && FlightSetup.read().collector);
assert.equal($('quickResult').hidden, false);
assert.equal($('quickIssue').hidden, true);
assert.equal($('quickSpeedRow').hidden, false);
const solarBefore = JSON.stringify(state);
QuickFlight.toggle('burst');
assert.equal(FlightSetup.read().burst, false, 'Solar burst stays forbidden');
assert.equal(JSON.stringify(state), solarBefore, 'the Solar warning cannot change settings, fuel or plans');
assert.equal($('infoDialog').open, true);
assert.ok($('dialogContent').innerHTML.includes('Солнце нельзя взрывать.'));
$('infoDialog').close();
assert.equal(reserve(), 50);
state.current = 'alpha'; state.ship = Space.point(object('alpha').p3); state.selected = 'sirius';
QuickFlight.toggle('sail');
QuickFlight.toggle('burst');
assert.ok(FlightSetup.read().engine && FlightSetup.read().sail && FlightSetup.read().burst && !FlightSetup.read().collector);
QuickFlight.toggle('collector');
assert.ok(FlightSetup.read().collector && FlightSetup.read().burst && FlightSetup.read().engine);
state.flightSetup.arrivalFuelPercent = 35; state.flightSetup.enginePowerW = 3e12;
QuickFlight.toggle('burst');
assert.equal(reserve(), 35); assert.equal(FlightSetup.read().enginePowerW, 3e12);
// An old zero preset changes the next-start preference, never an executing plan or the fuel on board.
reset(); state.flightSetup = FlightSetup.normalize({...FlightSetup.defaults(), arrivalFuelPercent: 0}); launch();
Simulation.tick(state.flight.mission.proper * .1);
const physical = () => JSON.stringify([state.flight, state.ship, state.matter, state.beta, state.proper, state.earth, state.universeElapsed]);
const before = physical(), old = JSON.parse(JSON.stringify(state)); delete old.reserveDefaultsVersion;
state = restore(old);
assert.equal(physical(), before); assert.equal(reserve(), 50); assert.equal(FlightSetup.read().arrivalFuelPercent, 0);
Simulation.tick(FlightEstimate.get().proper * 1.00001);
assert.equal(state.current, 'alpha'); assert.equal(state.matter, 0); assert.equal(reserve(), 50);
state.flightSetup.arrivalFuelPercent = 0;
state = restore(JSON.parse(JSON.stringify(state)));
assert.equal(reserve(), 0, 'an explicit new choice in the detailed plan survives reload');
const custom = {...initial(), flightSetup: FlightSetup.normalize({...FlightSetup.defaults(), arrivalFuelPercent: 35})}; delete custom.reserveDefaultsVersion;
custom.nextTargets = [{id:'sirius', setup:FlightSetup.normalize({...FlightSetup.defaults(), arrivalFuelPercent:0})}];
state = restore(custom); assert.equal(reserve(), 35); assert.equal(state.nextTargets[0].setup.arrivalFuelPercent, 0, 'existing queued plans retain explicit reserves');
// Two real default trips retain half the actual tank, not just a label in the forecast.
for (const target of ['alpha', 'proxima']) {
 reset(); state.selected = target;
 const p = MissionPlanner.preview(); assert.ok(p.valid, p.reason); assert.equal(p.setup.arrivalFuelPercent, 50); assert.ok(Math.abs(p.arrivalFuelKg - .5) < 1e-10);
 launch(); const active = state.flight; const frozen = physical();
 select('sirius'); QuickFlight.toggle('collector');
 assert.equal(state.flight, active); assert.equal(physical(), frozen);
 assert.equal(FlightQueue.setupFor('sirius').arrivalFuelPercent, 50);
 QuickFlight.toggle('engine');
 assert.equal(physical(), frozen); assert.equal(FlightQueue.setupFor('sirius').arrivalFuelPercent, 50);
 FlightQueue.dismiss(); Simulation.tick(state.flight.mission.proper * 1.00001);
 assert.equal(state.current, target); assert.ok(Math.abs(state.matter * 1000 - .5) < 1e-10);
}
assert.ok(FlightBuilder.reserveNote({valid:true, reserveLimited:true, arrivalFuelKg:.123, setup:{capacityKg:1}, requestedArrivalFuelPercent:50}).includes('12,3%'));
assert.equal(FlightBuilder.reserveNote({valid:true}), '');
assert.equal(QuickFlight.issueLabel({valid:true, arrivalFuelKg:.123, setup:{capacityKg:1}}), 'Запас 12,3%');
assert.equal(QuickFlight.issueLabel({valid:false, unreachable:true}), 'Недостижимо');
assert.equal(QuickFlight.issueLabel({valid:false, reason:'Тяги недостаточно для выхода из поля звезды.'}), 'Не хватает тяги');
console.log('PASS additive flight options/dependencies, Solar burst guard, preserved custom settings and active trajectory, one-time reserve migration, explicit new zero and real half-tank arrivals at both Centauri targets');
}`);
const html = fs.readFileSync('dist/index.html', 'utf8');
assert.ok(html.indexOf('id="quickFlight"') < html.indexOf('id="arrivalEstimate"'));
assert.equal((html.match(/data-flight-option=/g) || []).length, 4);
assert.ok(!html.includes('data-flight-mode=') && !html.includes('data-flight-reserve='));
