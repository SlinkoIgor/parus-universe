#!/usr/bin/env python3
"""Deterministic offline build of verified Wikipedia links and lazy media."""
import hashlib
import json
from collections import defaultdict
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'data-tools/sky-sources'
encode = lambda data: json.dumps(data, ensure_ascii=False, separators=(',', ':'), sort_keys=True)
digest = lambda text: hashlib.sha256(text.encode()).hexdigest()[:12]


def build():
    source = json.loads((SRC / 'wikipedia.json').read_text())
    records = source['records']
    by_object, articles, media, media_targets = defaultdict(list), {}, {}, defaultdict(set)
    observations = set()
    for r in records:
        id = str(r['pageId'])
        articles[id] = [r['title'] if r.get('language', 'en') == 'en' else '', r.get('russianTitle') or '']
        for oid in r['matches']:
            by_object[oid].append(id)
        if r.get('media'):
            p = r['media']
            media[p['id']] = p
            for oid in r.get('mediaObjects', r['matches']):
                media_targets[oid].add(p['id'])
            if p['mediaType'] == 'observation' and p.get('mediaKind') != 'survey':
                observations.add(p['id'])
    # Conflicting article identities are reviewable in the audit. Do not select
    # an arbitrary article simply because its response arrived first.
    ambiguous = {oid: ids for oid, ids in by_object.items() if len(set(ids)) != 1}
    for oid in ambiguous:
        media_targets.pop(oid, None)
    targets = {oid: ids[0] for oid, ids in by_object.items() if oid not in ambiguous}
    contextual = SRC / 'wikipedia-gallery.json'
    if contextual.exists():
        for p in json.loads(contextual.read_text())['records']:
            media[p['id']] = {k: v for k, v in p.items() if k not in ('objects', 'identification')}
            for oid in p['objects']:
                media_targets[oid].add(p['id'])
    used = {id for ids in media_targets.values() for id in ids}
    observations = {id for id in used if media[id]['mediaType'] == 'observation' and media[id].get('mediaKind') != 'survey'}
    depicted = defaultdict(list)
    for oid, ids in sorted(media_targets.items()):
        for id in ids:
            depicted[id].append(oid)
    buckets = defaultdict(dict)
    for id in sorted(used):
        buckets[hashlib.sha256(id.encode()).hexdigest()[0]][id] = dict(media[id], objects=depicted[id])
    files = {}
    for shard, photos in sorted(buckets.items()):
        content = encode(dict(version=1, photos=photos)) + '\n'
        name = 'wikipedia-media-' + shard + '.json'
        (ROOT / 'dist' / name).write_text(content)
        files[shard] = dict(url=name + '?v=' + digest(content), count=len(photos))
    used_articles = set(targets.values())
    data = dict(version=1, catalogueRevision=source['catalogueRevision'], targets=targets,
                articles={id: a for id, a in articles.items() if id in used_articles},
                mediaTargets={oid: sorted(ids) for oid, ids in media_targets.items()},
                shards={id: hashlib.sha256(id.encode()).hexdigest()[0] for id in sorted(used)},
                observations=sorted(observations & used), files=files)
    data['revision'] = digest(encode(data))
    content = "'use strict';\n// Generated by data-tools/build-wikipedia-media.py; see docs/sky-guide.md.\nconst WIKIPEDIA_INDEX=" + encode(data) + ';\n'
    (ROOT / 'dist/wikipedia-index.js').write_text(content)
    audit = dict(articles=len(data['articles']), linkedObjects=len(targets), images=len(used), illustratedObjects=len(media_targets),
                 ambiguous={oid: [articles[id][0] or articles[id][1] for id in ids] for oid, ids in ambiguous.items()})
    (SRC / 'wikipedia-audit.json').write_text(json.dumps(audit, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({k: v for k, v in audit.items() if k != 'ambiguous'}), 'ambiguous:', len(ambiguous))


if __name__ == '__main__':
    build()
