// Published disk models shared by catalogue placement and contour projection.
import fs from 'node:fs';
import crypto from 'node:crypto';
const models=JSON.parse(fs.readFileSync('data-tools/galaxy-disk-models.json','utf8'));
const output="'use strict';\n// Generated by data-tools/build-map-geometry-data.mjs. Angles: ICRS north through east.\nconst MAP_GEOMETRY_MODELS="+JSON.stringify(models)+';\n';
fs.writeFileSync('dist/map-geometry-data.js',output);
const path='dist/index.html',html=fs.readFileSync(path,'utf8'),hash=crypto.createHash('sha256').update(output).digest('hex').slice(0,12),updated=html.replace(/(map-geometry-data\.js\?v=)[^"]+/g,(_,prefix)=>prefix+hash);
if(updated!==html)fs.writeFileSync(path,updated);
