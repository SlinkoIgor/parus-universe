// Deterministic constrained t-SNE: true 3D affinities, fixed solar radii,
// Galactic-plane anchors, bounded azimuth changes. No third-party runtime.
import fs from 'node:fs';
import vm from 'node:vm';
const ctx=vm.createContext({console});
vm.runInContext(['catalog','astronomy','catalog-import','coordinates'].map(n=>fs.readFileSync('dist/'+n+'.js','utf8')).join('\n'),ctx);
const objects=vm.runInContext('OBJECTS.filter(o=>o.p3&&o.d>0).map(o=>({id:o.id,p3:o.p3,d:Math.hypot(...o.p3)}))',ctx);
const groups=[objects.filter(o=>o.d<100),objects.filter(o=>o.d>=100&&o.d<1e5),objects.filter(o=>o.d>=1e5&&o.d<1e8),objects.filter(o=>o.d>=1e8)];
const entries={},diagnostics=[];
for(const group of groups){
 const n=group.length;if(!n)continue;
 const scale=group.map(o=>o.d).sort((a,b)=>a-b)[Math.floor(n/2)];
 const r=group.map(o=>o.d/scale),angles=group.map(o=>Math.atan2(-o.p3[1],o.p3[0]));
 const limits=group.map(o=>o.id==='sgr'?0:Math.PI/3*Math.abs(o.p3[2])/o.d),P=new Float64Array(n*n);
 const perplexity=Math.min(20,Math.max(1,n-1));
 for(let i=0;i<n;i++){
  const ds=group.map((o,j)=>j===i?Infinity:o.p3.reduce((s,v,k)=>s+((v-group[i].p3[k])/scale)**2,0));
  const min=Math.min(...ds);let precision=1,lo=0,hi=Infinity,weights;
  for(let it=0;it<65;it++){
   weights=ds.map(v=>Number.isFinite(v)?Math.exp(-(v-min)*precision):0);const sum=weights.reduce((a,b)=>a+b,0)||1;
   const entropy=Math.log(sum)+precision*weights.reduce((s,w,j)=>s+(w?(ds[j]-min)*w:0),0)/sum;
   if(Math.abs(entropy-Math.log(perplexity))<1e-7)break;
   if(entropy>Math.log(perplexity)){lo=precision;precision=Number.isFinite(hi)?(lo+hi)/2:precision*2;}else{hi=precision;precision=(lo+hi)/2;}
  }
  const sum=weights.reduce((a,b)=>a+b,0)||1;for(let j=0;j<n;j++)P[i*n+j]=weights[j]/sum;
 }
 for(let i=0;i<n;i++)for(let j=i+1;j<n;j++)P[i*n+j]=P[j*n+i]=(P[i*n+j]+P[j*n+i])/(2*n);
 const penalty=.04;
 function evaluate(offsets,grad=false){
  const a=angles.map((v,i)=>v+offsets[i]),x=a.map((v,i)=>r[i]*Math.cos(v)),y=a.map((v,i)=>r[i]*Math.sin(v));
  const q=new Float64Array(n*n);let sum=0,cost=0;const g=new Float64Array(n);
  for(let i=0;i<n;i++)for(let j=i+1;j<n;j++){const v=1/(1+(x[i]-x[j])**2+(y[i]-y[j])**2);q[i*n+j]=v;sum+=2*v;}
  for(let i=0;i<n;i++)for(let j=i+1;j<n;j++){
   const v=q[i*n+j],p=P[i*n+j],prob=v/sum;if(p)cost+=2*p*Math.log(p/prob);
   if(grad){const f=4*(p-prob)*v,dx=x[i]-x[j],dy=y[i]-y[j];g[i]+=f*(-dx*y[i]+dy*x[i]);g[j]+=f*(dx*y[j]-dy*x[j]);}
  }
  for(let i=0;i<n;i++){cost+=penalty*offsets[i]**2/n;g[i]+=2*penalty*offsets[i]/n;}
  return{cost,g};
 }
 let offsets=Array(n).fill(0),initial=evaluate(offsets).cost,last=initial;
 for(let iteration=0;iteration<400;iteration++){
  const {g}=evaluate(offsets,true);let step=n*.7,accepted=false;
  for(let trial=0;trial<12;trial++){
   const next=offsets.map((o,i)=>Math.max(-limits[i],Math.min(limits[i],o-Math.max(-.08,Math.min(.08,g[i]*step)))));
   const cost=evaluate(next).cost;if(cost<=last){const change=last-cost;offsets=next;last=cost;accepted=true;if(change<1e-10)iteration=400;break;}step*=.5;
  }if(!accepted)break;
 }
 group.forEach((o,i)=>entries[o.id]={offset:offsets[i]});
 diagnostics.push({n,scale,perplexity,initialKL:initial,finalKL:last});
}
fs.writeFileSync('dist/layout-data.js','// Generated by data-tools/create-layout.mjs. Physical coordinates are untouched.\nconst LAYOUT_DATA='+JSON.stringify({method:'Constrained t-SNE',version:1,diagnostics,entries})+';\n');
console.log(JSON.stringify(diagnostics,null,2));
